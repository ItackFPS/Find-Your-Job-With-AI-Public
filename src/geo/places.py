"""Resolve a job's location text to a French place with coordinates, offline.

Backs the distance-based location model (update plan §C2): the user picks a home
place and a maximum distance; each offer's location is resolved here and the
distance is computed with :func:`distance_km`.

Data: ``src/geo/data/communes.csv.gz`` (every current French commune with its
centroid) and ``departements.csv`` (geo.api.gouv.fr, Licence Ouverte 2.0),
regenerated by ``scripts/build_geo_data.py``. Loaded lazily, once per process.
Standard library only, so importing it stays cheap.

Formats handled (all seen in collected offers): ``"13 - Aix-en-Provence"``
(France Travail), ``"Lyon, Auvergne-Rhône-Alpes, France"`` (LinkedIn, HelloWork),
``"29200 Brest"`` and ``"Bagneux (92)"`` (Indeed), ``"Paris 01"`` and ``"Lyon 3e"``
(arrondissements), a bare département or region code/name, and ``"France"``.

The resolver never guesses: a homonym it cannot separate (several communes named
"Saint-Denis" with no département, postcode or region to choose between them)
falls back to the département when one is known, else to "unknown". Precision is
always reported, so callers can tell a town from a département centroid.
"""

from __future__ import annotations

import csv
import gzip
import math
import re
import threading
import unicodedata
from dataclasses import dataclass
from pathlib import Path

_DATA = Path(__file__).resolve().parent / "data" / "communes.csv.gz"
_DEPTS = Path(__file__).resolve().parent / "data" / "departements.csv"

COMMUNE = "commune"
DEPARTMENT = "department"
REGION = "region"
COUNTRY = "country"

# INSEE region codes (2016 regions) -> name, for "City, Region, France" strings.
REGIONS: dict[str, str] = {
    "01": "Guadeloupe", "02": "Martinique", "03": "Guyane", "04": "La Réunion",
    "06": "Mayotte", "11": "Île-de-France", "24": "Centre-Val de Loire",
    "27": "Bourgogne-Franche-Comté", "28": "Normandie", "32": "Hauts-de-France",
    "44": "Grand Est", "52": "Pays de la Loire", "53": "Bretagne",
    "75": "Nouvelle-Aquitaine", "76": "Occitanie", "84": "Auvergne-Rhône-Alpes",
    "93": "Provence-Alpes-Côte d'Azur", "94": "Corse",
}
# Older or common alternative names seen in postings.
_REGION_ALIASES = {
    "paca": "93", "provence alpes cote d azur": "93", "region sud": "93", "sud": "93",
    "ile de france": "11", "idf": "11", "rhone alpes": "84", "auvergne": "84",
    "aquitaine": "75", "midi pyrenees": "76", "languedoc roussillon": "76",
    "nord pas de calais": "32", "picardie": "32", "alsace": "44", "lorraine": "44",
    "champagne ardenne": "44", "bourgogne": "27", "franche comte": "27",
    "haute normandie": "28", "basse normandie": "28", "centre": "24",
    "poitou charentes": "75", "limousin": "75", "reunion": "04",
    # English names (LinkedIn writes "Lyon, Auvergne-Rhône-Alpes" but "Rouen, Normandy").
    "normandy": "28", "brittany": "53", "burgundy": "27", "corsica": "94",
    "centre loire valley": "24", "french guiana": "03",
}
_FRANCE_WORDS = {"france", "fr", "fra", "metropole", "france metropolitaine"}
_ARRONDISSEMENT_RE = re.compile(
    r"^(paris|lyon|marseille)\s*(\d{1,2})\s*(?:e|er|eme|ème|arr\w*)?$")
_POSTCODE_RE = re.compile(r"(?<!\d)(\d{5})(?!\d)")
# Explicit département evidence only: "Bagneux (92)" or "92 - Bagneux". A city-name
# lookup is not evidence here (it would turn every "Saint-Denis" into the 93).
_DEPT_PARENS_RE = re.compile(r"\((\d{2,3}|2[AB])\)", re.I)
_DEPT_LEAD_RE = re.compile(r"^\s*(\d{2,3}|2[AB])\s*[-–]\s", re.I)
_SPLIT_RE = re.compile(r"\s*(?:,|/|\||;|\(|\)|\s-\s|\s–\s)\s*")


@dataclass(frozen=True)
class Place:
    """A resolved place. ``lat``/``lon`` are None only at country precision."""

    name: str
    precision: str            # commune | department | region | country
    lat: float | None
    lon: float | None
    department: str | None = None
    region: str | None = None
    insee: str | None = None
    # "exact" unless a homonym was chosen only because it is by far the largest.
    confidence: str = "exact"


@dataclass(frozen=True)
class _Commune:
    insee: str
    name: str
    postcodes: tuple[str, ...]
    department: str
    region: str
    population: int
    lat: float
    lon: float


def normalize(text: str) -> str:
    """Lowercase, no accents, hyphens/apostrophes as spaces, "st" -> "saint"."""
    nfd = unicodedata.normalize("NFD", text.lower())
    s = "".join(c for c in nfd if unicodedata.category(c) != "Mn")
    s = re.sub(r"[-'’`.]", " ", s)
    s = re.sub(r"\bste\b", "sainte", re.sub(r"\bst\b", "saint", s))
    return re.sub(r"\s+", " ", s).strip()


class _Index:
    def __init__(self) -> None:
        self.by_name: dict[str, list[_Commune]] = {}
        self.by_postcode: dict[str, list[_Commune]] = {}
        self.by_insee: dict[str, _Commune] = {}
        self.dept_centroid: dict[str, tuple[float, float]] = {}
        self.region_centroid: dict[str, tuple[float, float]] = {}
        with gzip.open(_DATA, "rt", encoding="utf-8", newline="") as f:
            for row in csv.DictReader(f):
                c = _Commune(row["insee"], row["name"], tuple(row["postcodes"].split()),
                             row["department"], row["region"], int(row["population"]),
                             float(row["lat"]), float(row["lon"]))
                self.by_insee[c.insee] = c
                self.by_name.setdefault(normalize(c.name), []).append(c)
                for pc in c.postcodes:
                    self.by_postcode.setdefault(pc, []).append(c)
        with _DEPTS.open(encoding="utf-8", newline="") as f:
            rows = list(csv.DictReader(f))
        self.dept_name: dict[str, str] = {r["code"]: r["name"] for r in rows}
        self.dept_region: dict[str, str] = {r["code"]: r["region"] for r in rows}
        self.dept_by_name: dict[str, str] = {normalize(r["name"]): r["code"] for r in rows}
        for attr, target in (("department", self.dept_centroid), ("region", self.region_centroid)):
            acc: dict[str, list[float]] = {}
            for c in self.by_insee.values():
                w = max(c.population, 1)
                a = acc.setdefault(getattr(c, attr), [0.0, 0.0, 0.0])
                a[0] += c.lat * w
                a[1] += c.lon * w
                a[2] += w
            for code, (la, lo, total) in acc.items():
                target[code] = (la / total, lo / total)


_index: _Index | None = None
_lock = threading.Lock()


def _idx() -> _Index:
    global _index
    if _index is None:
        with _lock:
            if _index is None:
                _index = _Index()
    return _index


def distance_km(a: tuple[float, float], b: tuple[float, float]) -> float:
    """Great-circle distance in km between two (lat, lon) points."""
    lat1, lon1, lat2, lon2 = map(math.radians, (*a, *b))
    h = (math.sin((lat2 - lat1) / 2) ** 2
         + math.cos(lat1) * math.cos(lat2) * math.sin((lon2 - lon1) / 2) ** 2)
    return 2 * 6371.0088 * math.asin(min(1.0, math.sqrt(h)))


def _commune_place(c: _Commune, confidence: str = "exact") -> Place:
    return Place(c.name, COMMUNE, c.lat, c.lon, c.department, c.region, c.insee, confidence)


def _explicit_department(text: str) -> str | None:
    for regex in (_DEPT_PARENS_RE, _DEPT_LEAD_RE):
        m = regex.search(text)
        if m and m.group(1).upper() in _idx().dept_name:
            return m.group(1).upper()
    return None


def department_place(code: str) -> Place | None:
    """The population-weighted centre of a département."""
    idx = _idx()
    centre = idx.dept_centroid.get(code)
    if centre is None or code not in idx.dept_name:
        return None
    return Place(idx.dept_name[code], DEPARTMENT, centre[0], centre[1], code, idx.dept_region.get(code))


def _region_code(part: str) -> str | None:
    n = normalize(part)
    for code, name in REGIONS.items():
        if normalize(name) == n:
            return code
    return _REGION_ALIASES.get(n)


def _pick(candidates: list[_Commune], dept: str | None, region: str | None,
          text_norm: str) -> tuple[_Commune, str] | None:
    """One commune among homonyms (with a confidence), or None when the evidence
    cannot separate them."""
    for key, value in (("department", dept), ("region", region)):
        if value:
            narrowed = [c for c in candidates if getattr(c, key) == value]
            if not narrowed:  # stated evidence rules out every candidate
                return None
            if len(narrowed) == 1:
                return narrowed[0], "exact"
            candidates = narrowed
    if len(candidates) == 1:
        return candidates[0], "exact"
    named = [c for c in candidates if normalize(c.name) in text_norm]
    if len(named) == 1:
        return named[0], "exact"
    ranked = sorted(candidates, key=lambda c: c.population, reverse=True)
    # A town against villages of the same name ("Bagneux" 92 vs five villages):
    # only when the largest is clearly the one postings mean. Reported as "likely".
    if ranked[0].population >= 10_000 and ranked[0].population >= 10 * max(ranked[1].population, 1):
        return ranked[0], "likely"
    return None


def resolve_place(text: str | None, countries: list[str] | None = None) -> Place | None:
    """Resolve a location string to a French :class:`Place`, or None if unknown.

    ``countries`` (the job's country list, when the source gives one) stops a
    foreign location from being matched to a French commune of the same name.
    """
    if not text or not text.strip():
        return None
    if countries and not any(normalize(c) in _FRANCE_WORDS for c in countries):
        return None
    idx = _idx()
    raw = text.strip()
    text_norm = normalize(raw)
    postcodes = _POSTCODE_RE.findall(raw)
    # Postcodes are read separately; without them "31057 Toulouse" (a CEDEX code
    # that matches no commune) still leaves "toulouse" to look up by name.
    parts = [p for p in (normalize(x) for x in _SPLIT_RE.split(_POSTCODE_RE.sub(" ", raw))) if p]
    parts = [p.removeprefix("canton of ").removeprefix("canton de ") for p in parts]
    if parts and parts[-1] in _FRANCE_WORDS:
        parts = parts[:-1]
    elif len(parts) > 1 and _looks_foreign(parts[-1]):
        return None

    dept = _explicit_department(raw)
    region = next((code for p in parts if (code := _region_code(p))), None)

    for pc in postcodes:
        cands = idx.by_postcode.get(pc)
        if cands:
            picked = _pick(cands, None, None, text_norm)
            if picked is None:  # a postcode shared by several communes: the largest
                return _commune_place(max(cands, key=lambda c: c.population), "likely")
            return _commune_place(*picked)

    for part in parts:
        m = _ARRONDISSEMENT_RE.match(part)
        if m:
            part = m.group(1)
        cands = idx.by_name.get(part)
        if cands:
            picked = _pick(cands, dept, region, text_norm)
            if picked is not None:
                return _commune_place(*picked)
            break  # a known but ambiguous name: do not try weaker parts

    if dept is None:  # a département named on its own ("Var", "Haute-Garonne")
        dept = next((idx.dept_by_name[p] for p in parts if p in idx.dept_by_name), None)
    if dept is None and postcodes:  # an unknown (CEDEX) postcode still names its département
        prefix = postcodes[0][:3] if postcodes[0].startswith("97") else postcodes[0][:2]
        dept = prefix if prefix in idx.dept_name and prefix != "20" else None
    if dept:
        return department_place(dept)
    if region:
        la, lo = idx.region_centroid[region]
        return Place(REGIONS[region], REGION, la, lo, None, region)
    if not parts:  # only "France" (or a synonym)
        return Place("France", COUNTRY, None, None)
    return None


def search_communes(query: str, limit: int = 10) -> list[Place]:
    """Offline autocomplete over communes: name prefix (accent/case-insensitive) or
    postcode prefix, largest communes first. Empty list for a query under 2 chars."""
    q = normalize(query or "")
    if len(q) < 2:
        return []
    idx = _idx()
    limit = max(1, min(limit, 50))
    if q.isdigit():
        found = {c.insee: c for pc, cs in idx.by_postcode.items() if pc.startswith(q) for c in cs}
        matches = list(found.values())
    else:
        matches = [c for name, cs in idx.by_name.items() if name.startswith(q) for c in cs]
    matches.sort(key=lambda c: (normalize(c.name) != q, -c.population, c.name))
    return [_commune_place(c) for c in matches[:limit]]


def commune_by_insee(insee: str) -> Place | None:
    c = _idx().by_insee.get(insee)
    return _commune_place(c) if c is not None else None


def department_name(code: str) -> str | None:
    return _idx().dept_name.get(code)


def departments_within(centre: tuple[float, float], radius_km: float, road_factor: float = 1.0) -> list[str]:
    """Département codes with their centre or at least one commune within ``radius_km``
    of ``centre`` (distances are great-circle × ``road_factor``), sorted by code."""
    idx = _idx()
    out = {code for code, c in idx.dept_centroid.items()
           if distance_km(centre, c) * road_factor <= radius_km}
    for c in idx.by_insee.values():
        if c.department not in out and distance_km(centre, (c.lat, c.lon)) * road_factor <= radius_km:
            out.add(c.department)
    return sorted(code for code in out if code in idx.dept_name)


# Country names that end a "City, Region, Country" string. Only the ones seen in
# postings matter: they stop "Valencia, Spain" or "London, United Kingdom" from
# matching a French commune.
_FOREIGN = {
    "belgium", "belgique", "switzerland", "suisse", "luxembourg", "germany", "allemagne",
    "spain", "espagne", "italy", "italie", "united kingdom", "uk", "royaume uni",
    "netherlands", "pays bas", "portugal", "ireland", "united states", "usa", "us",
    "canada", "monaco", "morocco", "maroc", "tunisia", "tunisie", "poland", "pologne",
    "sweden", "austria", "denmark", "norway", "finland", "czechia", "romania",
}


def _looks_foreign(part: str) -> bool:
    return part in _FOREIGN
